"""ZIP Archive bundle exporter for SmartWarehouse AI reports."""

import io
import zipfile
import hashlib
import datetime
from typing import Dict, Any
import pandas as pd
from .csv_exporter import export_dataframe_to_csv
from .html_exporter import generate_executive_html_report
from analytics.models import AnalyticsSnapshot


def generate_report_zip_bundle(
    snapshot: AnalyticsSnapshot,
    title: str = "Executive Warehouse Operational Report",
    generated_by: str = "OPERATOR",
    df_fleet: pd.DataFrame = None,
    df_tasks: pd.DataFrame = None,
    df_incidents: pd.DataFrame = None,
) -> bytes:
    """Creates a zipped archive containing HTML report, CSV data exports, and a cryptographic MANIFEST."""
    zip_buffer = io.BytesIO()
    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S UTC")

    # Generate HTML report
    html_report = generate_executive_html_report(
        snapshot=snapshot,
        title=title,
        generated_by=generated_by,
        df_fleet=df_fleet,
        df_incidents=df_incidents,
    )

    # Generate CSV bytes
    fleet_csv = export_dataframe_to_csv(df_fleet) if df_fleet is not None else b""
    tasks_csv = export_dataframe_to_csv(df_tasks) if df_tasks is not None else b""
    incidents_csv = export_dataframe_to_csv(df_incidents) if df_incidents is not None else b""

    # Files dictionary
    files_to_zip = {
        "Executive_Report.html": html_report.encode("utf-8"),
        "Fleet_Status.csv": fleet_csv,
        "Task_Roster.csv": tasks_csv,
        "Incident_Log.csv": incidents_csv,
    }

    # Generate MANIFEST.txt
    manifest_lines = [
        "============================================================",
        " SMARTWAREHOUSE AI — EXECUTIVE REPORT BUNDLE MANIFEST",
        "============================================================",
        f"Report Title:       {title}",
        f"Generated By:       {generated_by}",
        f"Generation Time:    {now_str}",
        f"Simulation Step:    {snapshot.simulation_step}",
        "============================================================",
        "ARCHIVE CHECKSUMS (SHA-256):",
    ]

    for fname, data in files_to_zip.items():
        chk = hashlib.sha256(data).hexdigest()
        manifest_lines.append(f"  {fname:<24} : {chk}")

    manifest_lines.append("============================================================")
    manifest_bytes = "\n".join(manifest_lines).encode("utf-8")
    files_to_zip["MANIFEST.txt"] = manifest_bytes

    # Write to ZIP
    with zipfile.ZipFile(zip_buffer, "w", zipfile.ZIP_DEFLATED) as zf:
        for fname, data in files_to_zip.items():
            zf.writestr(fname, data)

    return zip_buffer.getvalue()
