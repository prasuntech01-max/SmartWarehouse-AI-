"""Executive Reporting and Multi-Format Export view."""

import streamlit as st
import pandas as pd
from typing import Any
from ui.components import render_section_header
from ui.auth_helper import check_permission
from reporting.builder import ReportBuilder
from persistence.repo import ReportRepo


def render_reports_page(analytics_service: Any) -> None:
    """Renders the executive report builder, CSV downloads, HTML print-to-PDF, and ZIP archives."""
    render_section_header(
        "Executive Reporting & Export Centre",
        "Generate audit-grade operational reports, CSV tables with formula-injection defense, and print-optimized executive HTML.",
        icon="📑",
    )

    can_export = check_permission("export_reports")
    if not can_export:
        st.warning("🔒 Generating reports and exporting CSV/ZIP bundles requires OPERATOR or ADMIN role.")

    col1, col2 = st.columns([1.5, 1.0])
    with col1:
        st.markdown("#### 📝 Configure & Generate Report")
        rep_title = st.text_input("Report Title", value="SmartWarehouse Operational Performance Report")
        operator_name = st.session_state.get("username", "operator").upper()

        if st.button("📄 Generate Report Package", key="btn_gen_rep", disabled=not can_export, use_container_width=True):
            with st.spinner("Generating analytical aggregates, HTML executive summary, and CSV data tables..."):
                builder = ReportBuilder(analytics_service)
                report_obj = builder.build_report(title=rep_title, generated_by=operator_name, persist=True)
                st.session_state["latest_report"] = report_obj
                st.success(f"Report `{report_obj['report_id']}` generated and recorded in audit log!")

    with col2:
        st.markdown("#### 📥 Download Center")
        latest_rep = st.session_state.get("latest_report")
        if latest_rep:
            st.download_button(
                label="🖨️ Download Executive HTML (Print-to-PDF)",
                data=latest_rep["html_document"],
                file_name=f"{latest_rep['report_id']}_Executive_Report.html",
                mime="text/html",
                use_container_width=True,
            )
            st.download_button(
                label="📦 Download Complete ZIP Bundle (CSV + HTML + SHA256)",
                data=latest_rep["zip_bundle"],
                file_name=f"{latest_rep['report_id']}_Bundle.zip",
                mime="application/zip",
                use_container_width=True,
            )
            col_csv1, col_csv2 = st.columns(2)
            with col_csv1:
                st.download_button(
                    label="📊 Fleet CSV",
                    data=latest_rep["fleet_csv"],
                    file_name="Fleet_Telemetry.csv",
                    mime="text/csv",
                    use_container_width=True,
                )
            with col_csv2:
                st.download_button(
                    label="📋 Tasks CSV",
                    data=latest_rep["tasks_csv"],
                    file_name="Task_Roster.csv",
                    mime="text/csv",
                    use_container_width=True,
                )
        else:
            st.info("Click 'Generate Report Package' to create downloadable deliverables.")

    # HTML Preview if report exists
    if latest_rep:
        st.divider()
        st.markdown("#### 👁️ Executive HTML Report Preview")
        st.components.v1.html(latest_rep["html_document"], height=650, scrolling=True)

    # Persisted Reports Audit Table
    st.divider()
    st.markdown("#### 📜 Persisted Report History (Audit Log)")
    try:
        saved_reps = ReportRepo.list_reports(limit=10)
        if saved_reps:
            r_rows = [{
                "Report ID": r["report_id"],
                "Title": r["title"],
                "Generated By": r["generated_by"],
                "Format": r["export_format"],
                "Timestamp": str(r["created_at"]),
            } for r in saved_reps]
            st.dataframe(pd.DataFrame(r_rows), use_container_width=True, hide_index=True)
        else:
            st.info("No prior report generation records stored in database.")
    except Exception:
        st.info("Report records table empty.")
